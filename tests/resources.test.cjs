'use strict';
const assert=require('node:assert/strict'),T=require('../core.js'),R=require('../resources.js');
const builtin=require('../builtin-assets.js'),fs=require('node:fs');
assert.deepEqual(Buffer.from(builtin['ui_skin.ppm'].data,'base64'),fs.readFileSync(__dirname+'/../examples/ui_skin.ppm'));
const d=T.initial(),c=T.widget('canvas','images');c.page='main';c.w=30;c.h=10;
c.paint=[{op:'image',...T.clone(T.Pixels.defaults.image),asset:{path:'/root/images/required.ppm',w:32,h:32,key:null,dither:false}}];
d.windows[0].widgets=[c];
// Reproduce importing the right filename into a project with the old alias.
d.assets=[{name:'asset_1.ppm',originalName:'required.ppm',data:'AAAA'}];
const geometry=JSON.stringify(c.paint),data=Buffer.from('P6\n1 1\n255\n\0\0\0').toString('base64');
const result=R.storeImage(d,{name:'required.ppm',originalName:'required.ppm',data,w:1,h:1});
assert.equal(result.name,'required.ppm');assert(result.linked);
assert.equal(JSON.stringify(c.paint),geometry,'Repair must preserve elements and their decoded dimensions');
assert(R.inventory(d).find(f=>f.name==='required.ppm').embedded);
assert.equal(d.assets.find(f=>f.name==='required.ppm').data,data);
R.storeImage(d,{name:'other.ppm',originalName:'other.png',data:'BBBB'},'required.ppm');
assert.equal(d.assets.filter(f=>f.name==='required.ppm').length,1);
assert.equal(d.assets.find(f=>f.name==='required.ppm').data,'BBBB');
const fresh=R.storeImage(d,{name:'new.ppm',originalName:'new.png',data});
assert(!fresh.linked);assert.equal(fresh.name,'new.ppm');
assert.equal(R.storeImage(d,{name:'new.ppm',originalName:'new.png',data}).name,'new.ppm');
d.assets.find(f=>f.name==='required.ppm').data='';
assert(!R.inventory(d).find(f=>f.name==='required.ppm').embedded);
assert(R.storeImage(d,{name:'required.ppm',originalName:'required.ppm',data}).linked);
assert.equal(R.inventory(d).find(f=>f.name==='required.ppm').uses[0].widgetId,'images');
d.modules=['controller'];d.binaryDependencies=[{name:'controller.mpy',data:'TQYAAA=='}];
d.assets.push({name:'notes.txt',mime:'text/plain',data:'VGV4dA=='});
assert.equal(R.inventory(d).find(f=>f.name==='controller.mpy').kind,'module');
assert(R.inventory(d).find(f=>f.name==='controller.mpy').required);
assert.equal(R.inventory(d).find(f=>f.name==='notes.txt').kind,'text');
assert.deepEqual(T.validate(T.parse(JSON.stringify(d))).errors,[]);
assert.throws(()=>R.storeImage(d,{name:'../bad.ppm',originalName:'bad.png',data}),/filename/);
c.paint.push({...T.clone(c.paint[0]),asset:{...c.paint[0].asset,path:'/other/required.ppm'}});
assert.throws(()=>R.required(d),/filenames must be unique/);
console.log('PASS: imported image repairs original references, legacy aliases, explicit relinking, replacements, geometry preservation and missing-resource inventory.');
